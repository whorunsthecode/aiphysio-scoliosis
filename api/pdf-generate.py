def render_template(content: dict, appointment_at: str, generated_at: str) -> str:
    li = lambda items: "".join(f"<li>{escape(x)}</li>" for x in items)
    return HTML_TEMPLATE.format(
        appointment_date=escape(appointment_at),
        generated_at=escape(generated_at),
        summary=escape(content.get("summary", "")),
        posture_items=li(content.get("posture_trends", [])),
        pain_items=li(content.get("pain_patterns", [])),
        compliance=escape(content.get("compliance", "")),
        question_items=li(content.get("questions_for_physio", [])),
        what_is_working=escape(content.get("what_is_working", "")),
    )


def escape(s: str) -> str:
    if s is None:
        return ""
    return (
        str(s)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def _bad_request(handler: BaseHTTPRequestHandler, message: str, status: int = 400):
    body = json.dumps({"error": message}).encode("utf-8")
    handler.send_response(status)
    handler.send_header("Content-Type", "application/json")
    handler.send_header("Content-Length", str(len(body)))
    handler.end_headers()
    handler.wfile.write(body)


class handler(BaseHTTPRequestHandler):
    def do_POST(self):  # noqa: N802
        try:
            length = int(self.headers.get("Content-Length", "0"))
            if length <= 0:
                return _bad_request(self, "empty body")
            payload = json.loads(self.rfile.read(length))

            content = payload.get("content")
            appointment_id = payload.get("appointmentId")
            if not content or not appointment_id:
                return _bad_request(self, "content and appointmentId are required")

            if HTML is None:
                return _bad_request(self, "weasyprint not installed", 500)
            if create_client is None or not SUPABASE_URL or not SUPABASE_KEY:
                return _bad_request(self, "supabase client not configured", 500)

            html_str = render_template(
                content,
                appointment_at=payload.get("appointment_at", "(date not provided)"),
                generated_at=payload.get("generated_at", ""),
            )
            pdf_bytes = HTML(string=html_str).write_pdf()
            if not pdf_bytes:
                return _bad_request(self, "pdf generation returned empty", 502)

            supabase = create_client(SUPABASE_URL, SUPABASE_KEY)
            storage_path = f"liaison/{appointment_id}.pdf"
            try:
                supabase.storage.from_(BUCKET).remove([storage_path])
            except Exception:
                pass
            supabase.storage.from_(BUCKET).upload(
                storage_path,
                pdf_bytes,
                {"content-type": "application/pdf", "upsert": "true"},
            )

            body = json.dumps({"pdfStoragePath": storage_path}).encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
        except Exception as exc:  # noqa: BLE001
            _bad_request(self, f"pdf generation failed: {exc}", 500)
