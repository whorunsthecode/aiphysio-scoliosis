"""
Vercel Python serverless function for Liaison physio-handoff PDF rendering.

Receives JSON content from the Liaison agent, renders a clean physio-doc HTML
template, converts to PDF via WeasyPrint, uploads to Supabase Storage, and
returns the storage path.

Locally `next dev` does NOT run Python — Liaison detects this and proceeds
with content_summary saved to the row, no PDF attached. On Vercel both
co-exist and Liaison's flow completes end-to-end.
"""

